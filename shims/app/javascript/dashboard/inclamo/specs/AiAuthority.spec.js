import { mount, flushPromises } from '@vue/test-utils';
import AiPolicyEditor from '../components/AiPolicyEditor.vue';
import AiProposalReview from '../components/AiProposalReview.vue';
import InclamoAPI from '../api';
vi.mock('../api', () => ({ default: { getAiPolicies: vi.fn(), setAiPolicy: vi.fn(), getAiProposals: vi.fn(), reviewAiProposal: vi.fn() } }));
const policies = { currency: 'USD', allowed_states: ['UNFULFILLED', 'FULFILLED'], policies: [{ action: 'refund', mode: 'propose', limits: {} }, { action: 'address', mode: 'forbidden', limits: {} }] };
const proposal = { id: 1, state: 'proposed', action: 'address', review_digest: 'review-1', request: { params: {}, address: { address1: '17 Test Lane' } }, summary: { order_number: '#1001', effect: {}, order_total: { amount: '125.00', currencyCode: 'USD' } }, initiator: { name: 'AI helper' }, can_approve: true, expired: false, expires_at: '2026-11-10T10:00:00Z' };
beforeEach(() => {
  vi.clearAllMocks();
  InclamoAPI.getAiPolicies.mockResolvedValue({ data: structuredClone(policies) });
  InclamoAPI.getAiProposals.mockResolvedValue({ data: { proposals: [{ ...proposal }] } });
});
it('shows default approval and requires explicit autonomous limits', async () => {
  const wrapper = mount(AiPolicyEditor);
  await flushPromises();
  const row = wrapper.find('[data-testid="inclamo-ai-policy-refund"]');
  expect(row.find('select').element.value).toBe('propose');
  expect(row.find('input').exists()).toBe(false);
  await row.find('select').setValue('autonomous');
  expect(row.find('[data-testid="ai-max-amount"]').attributes('required')).toBeDefined();
  expect(row.text()).toContain('Maximum current order total');
  await row.find('[data-testid="ai-max-amount"]').setValue('50');
  await row.find('input[type="checkbox"]').setValue(true);
  InclamoAPI.setAiPolicy.mockRejectedValue({ response: { data: { message: 'Select a valid restriction' } } });
  await row.trigger('submit');
  await flushPromises();
  expect(InclamoAPI.setAiPolicy).toHaveBeenCalledWith('refund', { mode: 'autonomous', limits: { currency: 'USD', max_amount: 50, allowed_states: ['UNFULFILLED'] } });
  expect(wrapper.text()).toContain('Select a valid restriction');
  expect(row.find('select').element.value).toBe('autonomous');
  expect(wrapper.find('[data-testid="inclamo-ai-policy-address"] select').element.value).toBe('forbidden');
});
it('keeps another unsaved operation intact when a policy is saved', async () => {
  const wrapper = mount(AiPolicyEditor);
  await flushPromises();
  await wrapper.find('[data-testid="inclamo-ai-policy-address"] select').setValue('propose');
  InclamoAPI.setAiPolicy.mockResolvedValue({ data: structuredClone(policies) });
  await wrapper.find('[data-testid="inclamo-ai-policy-refund"]').trigger('submit');
  await flushPromises();
  expect(wrapper.find('[data-testid="inclamo-ai-policy-address"] select').element.value).toBe('propose');
});
it('shows the exact requested change and submits the shown review digest', async () => {
  const wrapper = mount(AiProposalReview, { props: { conversationId: 7 } });
  await flushPromises();
  expect(wrapper.text()).toContain('17 Test Lane');
  expect(wrapper.text()).toContain('125');
  expect(wrapper.text()).not.toContain('[object Object]');
  InclamoAPI.reviewAiProposal.mockRejectedValue({ response: { data: { error: 'review_changed' } } });
  await wrapper.find('[data-testid="ai-approve"]').trigger('click');
  await flushPromises();
  expect(InclamoAPI.reviewAiProposal).toHaveBeenCalledWith(7, 1, 'approve', { review_digest: 'review-1' });
  expect(wrapper.text()).toContain('Refresh and review it');
  InclamoAPI.reviewAiProposal.mockResolvedValue({ data: { ...proposal, review_digest: 'review-2' } });
  InclamoAPI.getAiProposals.mockResolvedValue({ data: { proposals: [{ ...proposal, review_digest: 'review-2' }] } });
  await wrapper.find('[data-testid="ai-refresh"]').trigger('click');
  await flushPromises();
  await wrapper.find('[data-testid="ai-approve"]').trigger('click');
  await flushPromises();
  expect(InclamoAPI.reviewAiProposal).toHaveBeenLastCalledWith(7, 1, 'approve', { review_digest: 'review-2' });
});
it('disables approval for missing rights and expired proposals while permitting refresh and rejection', async () => {
  InclamoAPI.getAiProposals.mockResolvedValue({ data: { proposals: [{ ...proposal, can_approve: false, expired: true }] } });
  const wrapper = mount(AiProposalReview, { props: { conversationId: 7 } });
  await flushPromises();
  expect(wrapper.find('[data-testid="ai-approve"]').element.disabled).toBe(true);
  expect(wrapper.find('[data-testid="ai-reject"]').element.disabled).toBe(false);
  expect(wrapper.find('[data-testid="ai-refresh"]').element.disabled).toBe(false);
  expect(wrapper.text()).toContain('Expired');
});
it('discards a delayed response after navigating to another conversation', async () => {
  let resolveFirst;
  InclamoAPI.getAiProposals.mockImplementationOnce(() => new Promise(resolve => { resolveFirst = resolve; })).mockResolvedValue({ data: { proposals: [] } });
  const wrapper = mount(AiProposalReview, { props: { conversationId: 7 } });
  await wrapper.setProps({ conversationId: 8 });
  await flushPromises();
  resolveFirst({ data: { proposals: [proposal] } });
  await flushPromises();
  expect(wrapper.text()).not.toContain('17 Test Lane');
});
it('reviews product names, quantity changes and money without exposing internal identifiers', async () => {
  const edit = { ...proposal, action: 'edit_items', request: { params: { lines: [{ line_item_id: 'gid://shopify/LineItem/7', quantity: 3 }] } }, summary: { ...proposal.summary, effect: { currency: 'USD', amount: '25.00', difference: 'owed', lines: [{ id: 'gid://shopify/LineItem/7', title: 'Ceramic mug', quantity_before: 1, quantity: 3, unit_price: { amount: '12.50', currency: 'USD' } }] } } };
  InclamoAPI.getAiProposals.mockResolvedValue({ data: { proposals: [edit] } });
  const wrapper = mount(AiProposalReview, { props: { conversationId: 7 } });
  await flushPromises();
  expect(wrapper.text()).toContain('Ceramic mug');
  expect(wrapper.text()).toContain('1 → 3');
  expect(wrapper.text()).toContain('Customer owes');
  expect(wrapper.text()).toContain('25.00');
  expect(wrapper.text()).not.toContain('gid://');
});
it('names refunded products and shows the payment destination and actual restocking outcome', async () => {
  const refund = { ...proposal, action: 'refund', request: { params: { mode: 'items', items: [{ line_item_id: 'gid://shopify/LineItem/7', quantity: 1 }] } }, summary: { ...proposal.summary, effect: { currency: 'USD', amount: '12.50', items: [{ title: 'Ceramic mug', quantity: 1 }], destinations: [{ gateway: 'Visa', amount: '12.50' }], restocked_items: 0, unplaced_items: 1 } } };
  InclamoAPI.getAiProposals.mockResolvedValue({ data: { proposals: [refund] } });
  const wrapper = mount(AiProposalReview, { props: { conversationId: 7 } });
  await flushPromises();
  expect(wrapper.text()).toContain('Ceramic mug');
  expect(wrapper.text()).toMatch(/Visa:.*12\.50/);
  expect(wrapper.text()).toContain('Items without a restock location');
  expect(wrapper.text()).not.toContain('gid://');
});
